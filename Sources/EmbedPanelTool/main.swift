// Writes the control panel's page as a Swift string: panel.html with
// panel.js put in place of its `<script src="panel.js">`. Run by the
// EmbedPanel plugin when either file changes.
//
// Usage: EmbedPanelTool <panel.html> <panel.js> <output.swift>

#if canImport(FoundationEssentials)
import FoundationEssentials
#else
import Foundation
#endif
#if canImport(Glibc)
import Glibc
#elseif canImport(Musl)
import Musl
#elseif canImport(Darwin)
import Darwin
#endif

let arguments = CommandLine.arguments
guard arguments.count == 4 else {
    print("usage: EmbedPanelTool <panel.html> <panel.js> <output.swift>")
    exit(2)
}

func read(_ path: String) -> String {
    guard let data = FileManager.default.contents(atPath: path) else {
        print("EmbedPanelTool: cannot read \(path)")
        exit(1)
    }
    return String(decoding: data, as: UTF8.self)
}

let marker = #"<script src="panel.js"></script>"#
let html = read(arguments[1])
let script = read(arguments[2])
guard html.ranges(of: marker).count == 1 else {
    print("EmbedPanelTool: \(arguments[1]) must load panel.js exactly once, as \(marker)")
    exit(1)
}
var page = html.replacing(marker, with: "<script>\n" + script + "</script>")
if !page.hasSuffix("\n") { page += "\n" }

// A raw string whose delimiter no `"#…` or `\#…` in the page can end or
// interpolate.
var longest = 0
var run = 0
var previous: Character = " "
for character in page {
    if character == "#", run > 0 || previous == "\"" || previous == "\\" {
        run += 1
        longest = max(longest, run)
    } else {
        run = 0
    }
    if character != "#" { previous = character }
}
let hashes = String(repeating: "#", count: longest + 1)

let output = """
// Generated by the EmbedPanel plugin from Panel/panel.html and
// Panel/panel.js; edit those.

extension AdminPage {
    static let html = \(hashes)\"\"\"
\(page)\"\"\"\(hashes)
}

"""
do {
    try output.write(toFile: arguments[3], atomically: true, encoding: .utf8)
} catch {
    print("EmbedPanelTool: cannot write \(arguments[3]): \(error)")
    exit(1)
}
