// Writes the control panel's page as a Swift string: panel.html with each
// script put in place of its `<script src="name.js">`. Run by the
// EmbedPanel plugin when any of the files changes.
//
// Usage: EmbedPanelTool <panel.html> <output.swift> <script.js>...

#if canImport(FoundationEssentials)
import FoundationEssentials
#else
import Foundation
#endif
#if canImport(Glibc)
import Glibc
#elseif canImport(Musl)
import Musl
#elseif canImport(Darwin)
import Darwin
#endif

let arguments = CommandLine.arguments
guard arguments.count >= 4 else {
    print("usage: EmbedPanelTool <panel.html> <output.swift> <script.js>...")
    exit(2)
}

func read(_ path: String) -> String {
    guard let data = FileManager.default.contents(atPath: path) else {
        print("EmbedPanelTool: cannot read \(path)")
        exit(1)
    }
    return String(decoding: data, as: UTF8.self)
}

var page = read(arguments[1])
for path in arguments[3...] {
    let name = path.split(separator: "/").last.map(String.init) ?? path
    let marker = "<script src=\"\(name)\"></script>"
    guard page.ranges(of: marker).count == 1 else {
        print("EmbedPanelTool: \(arguments[1]) must load \(name) exactly once, as \(marker)")
        exit(1)
    }
    page = page.replacing(marker, with: "<script>\n" + read(path) + "</script>")
}
if !page.hasSuffix("\n") { page += "\n" }

// A raw string whose delimiter no `"#…` or `\#…` in the page can end or
// interpolate.
var longest = 0
var run = 0
var previous: Character = " "
for character in page {
    if character == "#", run > 0 || previous == "\"" || previous == "\\" {
        run += 1
        longest = max(longest, run)
    } else {
        run = 0
    }
    if character != "#" { previous = character }
}
let hashes = String(repeating: "#", count: longest + 1)

let output = """
// Generated by the EmbedPanel plugin from Panel/panel.html and
// its scripts; edit those.

extension AdminPage {
    static let html = \(hashes)\"\"\"
\(page)\"\"\"\(hashes)
}

"""
do {
    try output.write(toFile: arguments[2], atomically: true, encoding: .utf8)
} catch {
    print("EmbedPanelTool: cannot write \(arguments[2]): \(error)")
    exit(1)
}
